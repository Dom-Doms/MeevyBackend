
CREATE TABLE flashcard (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                           user_id BIGINT NOT NULL,
                           subject_id BIGINT,

                           question TEXT NOT NULL,
                           answer TEXT NOT NULL,

                           created_at TIMESTAMPTZ NOT NULL,
                           updated_at TIMESTAMPTZ NOT NULL,

                           CONSTRAINT fk_flashcard_user
                               FOREIGN KEY (user_id)
                                   REFERENCES "user"(id),

                        --Se si elimina una materia, le flashcard rimangono salvate
                           CONSTRAINT fk_flashcard_subject
                               FOREIGN KEY (subject_id)
                                   REFERENCES subject(id)
                                   ON DELETE SET NULL
);

-- Per recuperare le flashcard di un utente, filtrando anche per materia
CREATE INDEX idx_flashcard_user_subject
    ON flashcard(user_id, subject_id);
