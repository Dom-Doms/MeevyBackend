
-- V5__create_personal_pomodoro_session.sql
--
-- Crea la tabella per le sessioni Pomodoro personali.
-- Ogni sessione appartiene a un utente e può essere
-- associata a una materia personale.

CREATE TABLE personal_pomodoro_session (

    -- Identificatore della sessione
                                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Proprietario e materia associata
                                           user_id BIGINT NOT NULL,
                                           subject_id BIGINT,

    -- Configurazione in secondi
                                           study_duration_seconds INTEGER NOT NULL,
                                           break_duration_seconds INTEGER NOT NULL,
                                           target_duration_seconds BIGINT NOT NULL,

    -- Stato della sessione
                                           status VARCHAR(20) NOT NULL DEFAULT 'READY',

    -- Informazioni temporali
                                           created_at TIMESTAMPTZ NOT NULL,
                                           started_at TIMESTAMPTZ,
                                           paused_at TIMESTAMPTZ,
                                           accumulated_pause_seconds BIGINT NOT NULL DEFAULT 0,
                                           ended_at TIMESTAMPTZ,

    -- Tempo di studio contabilizzato
                                           actual_study_seconds BIGINT NOT NULL DEFAULT 0,

    -- Relazione con User
                                           CONSTRAINT fk_personal_pomodoro_user
                                               FOREIGN KEY (user_id)
                                                   REFERENCES "user"(id),

    -- Relazione con Subject
                                           CONSTRAINT fk_personal_pomodoro_subject
                                               FOREIGN KEY (subject_id)
                                                   REFERENCES subject(id)
                                                   ON DELETE SET NULL,

    -- Durate obbligatoriamente positive
                                           CONSTRAINT chk_personal_pomodoro_durations
                                               CHECK (
                                                   study_duration_seconds > 0
                                                       AND break_duration_seconds > 0
                                                       AND target_duration_seconds > 0
                                                   ),

    -- I tempi accumulati non possono essere negativi
                                           CONSTRAINT chk_personal_pomodoro_times
                                               CHECK (
                                                   accumulated_pause_seconds >= 0
                                                       AND actual_study_seconds >= 0
                                                   ),

    -- Stati consentiti
                                           CONSTRAINT chk_personal_pomodoro_status
                                               CHECK (
                                                   status IN (
                                                              'READY',
                                                              'RUNNING',
                                                              'PAUSED',
                                                              'COMPLETED',
                                                              'CANCELLED'
                                                       )
                                                   )
);

-- Impedisce a un utente di avere più di una sessione in corso
CREATE UNIQUE INDEX uq_personal_pomodoro_active_user
    ON personal_pomodoro_session (user_id)
    WHERE status IN ('READY', 'RUNNING', 'PAUSED');

-- Ottimizza la ricerca dello storico per utente.
CREATE INDEX idx_personal_pomodoro_user_created
    ON personal_pomodoro_session (user_id, created_at DESC);

-- Ottimizza le ricerche per materia.
CREATE INDEX idx_personal_pomodoro_subject
    ON personal_pomodoro_session (subject_id);
