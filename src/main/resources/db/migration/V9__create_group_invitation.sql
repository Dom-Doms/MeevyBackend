
-- Inviti per accedere ai gruppi di studio.
CREATE TABLE group_invitation (

                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                  group_id BIGINT NOT NULL,

                                  created_by_user_id BIGINT NOT NULL,

    -- Hash SHA-256 del token presente nel link.
                                  token_hash VARCHAR(64) NOT NULL,

                                  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                  expires_at TIMESTAMPTZ NOT NULL,

    -- NULL = invito non ancora utilizzato.
                                  used_at TIMESTAMPTZ,

                                  used_by_user_id BIGINT,

                                  CONSTRAINT fk_group_invitation_group
                                      FOREIGN KEY (group_id) REFERENCES study_group(id)
                                          ON DELETE CASCADE,

                                  CONSTRAINT fk_group_invitation_created_by
                                      FOREIGN KEY (created_by_user_id) REFERENCES "user"(id),

                                  CONSTRAINT fk_group_invitation_used_by
                                      FOREIGN KEY (used_by_user_id) REFERENCES "user"(id),

                                  CONSTRAINT uk_group_invitation_token_hash
                                      UNIQUE (token_hash),

                                  CONSTRAINT ck_group_invitation_expiration
                                      CHECK (expires_at > created_at),

    -- Data e utente devono essere entrambi presenti oppure entrambi NULL.
                                  CONSTRAINT ck_group_invitation_usage
                                      CHECK (
                                          (used_at IS NULL AND used_by_user_id IS NULL)
                                              OR
                                          (used_at IS NOT NULL AND used_by_user_id IS NOT NULL)
                                          ),

                                  CONSTRAINT ck_group_invitation_used_at
                                      CHECK (
                                          used_at IS NULL
                                              OR
                                          (used_at >= created_at AND used_at < expires_at)
                                          )
);

-- Facilita la ricerca degli inviti di un gruppo.
CREATE INDEX idx_group_invitation_group_id
    ON group_invitation(group_id);
