
-- Ogni gruppo ha una sola chat, quindi non ci serve una tabella chat.
-- I messaggi rimangono anche se chi li ha scritti lascia il gruppo.

CREATE TABLE group_message (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                               group_id BIGINT NOT NULL,
                               sender_user_id BIGINT NOT NULL,

                               content VARCHAR(4000) NOT NULL,
                               created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                               CONSTRAINT fk_group_message_group
                                   FOREIGN KEY (group_id)
                                       REFERENCES study_group(id)
                                       ON DELETE CASCADE,

                               CONSTRAINT fk_group_message_sender
                                   FOREIGN KEY (sender_user_id)
                                       REFERENCES "user"(id),

    -- Non accettiamo messaggi vuoti o composti solo da spazi.
                               CONSTRAINT ck_group_message_content_not_blank
                                   CHECK (length(btrim(content)) > 0)
);

-- per recuperare velocemente gli ultimi messaggi e caricare quelli più vecchi quando si scorre la chat.
CREATE INDEX idx_group_message_group_id_id
    ON group_message(group_id, id DESC);
