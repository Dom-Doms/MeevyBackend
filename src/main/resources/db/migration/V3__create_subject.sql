
-- Crea la tabella delle materie personali degli utenti.
CREATE TABLE subject (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                         name VARCHAR(150) NOT NULL,

                         user_id BIGINT NOT NULL,

    -- Ogni materia deve appartenere a un utente esistente.
                         CONSTRAINT fk_subject_user
                             FOREIGN KEY (user_id)
                                 REFERENCES "user"(id)
);

-- Velocizza la ricerca delle materie di un utente.
CREATE INDEX idx_subject_user_id
    ON subject(user_id);
