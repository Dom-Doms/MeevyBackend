
-- Memorizza le sessioni di rinnovo dell'autenticazione.
CREATE TABLE refresh_token (

                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                               user_id BIGINT NOT NULL,

    -- Hash SHA-256 del token, rappresentato in esadecimale.
                               token_hash VARCHAR(64) NOT NULL,

                               created_at TIMESTAMPTZ NOT NULL,

                               expires_at TIMESTAMPTZ NOT NULL,

    -- NULL = token non revocato.
                               revoked_at TIMESTAMPTZ,

                               CONSTRAINT fk_refresh_token_user
                                   FOREIGN KEY (user_id)
                                       REFERENCES "user"(id),

                               CONSTRAINT uk_refresh_token_hash
                                   UNIQUE (token_hash),

                               CONSTRAINT ck_refresh_token_expiration
                                   CHECK (expires_at > created_at)
);

-- Facilita la ricerca delle sessioni di un utente.
CREATE INDEX idx_refresh_token_user_id
    ON refresh_token(user_id);
