-- Crea la checklist associata a una materia personale.
CREATE TABLE checklist (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                           subject_id BIGINT NOT NULL UNIQUE,

                           CONSTRAINT fk_checklist_subject
                               FOREIGN KEY (subject_id)
                                   REFERENCES subject(id)
                                   ON DELETE CASCADE
);

-- Crea le singole attività della checklist.
CREATE TABLE checklist_item (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                checklist_id BIGINT NOT NULL,

                                text TEXT NOT NULL,

                                completed BOOLEAN NOT NULL DEFAULT FALSE,

                                CONSTRAINT fk_checklist_item_checklist
                                    FOREIGN KEY (checklist_id)
                                        REFERENCES checklist(id)
                                        ON DELETE CASCADE
);

-- Velocizza il recupero delle attività di una checklist.
CREATE INDEX idx_checklist_item_checklist_id
    ON checklist_item(checklist_id);