
-- Crea la tabella delle risorse caricate dagli utenti.
-- Il contenuto fisico dei file viene salvato sul server,
-- mentre PostgreSQL conserva soltanto i metadati.

CREATE TABLE file_resource (

                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Proprietario e utente che ha caricato il file.
                               owner_user_id BIGINT NOT NULL,
                               uploaded_by_user_id BIGINT NOT NULL,

    -- Materia facoltativa.
                               subject_id BIGINT,

    -- Informazioni sul file.
                               original_filename VARCHAR(255) NOT NULL,
                               storage_key VARCHAR(255) NOT NULL,
                               content_type VARCHAR(120) NOT NULL,
                               size_bytes BIGINT NOT NULL,

    -- Data del caricamento.
                               created_at TIMESTAMPTZ NOT NULL,

    -- Relazione con il proprietario.
                               CONSTRAINT fk_file_resource_owner
                                   FOREIGN KEY (owner_user_id)
                                       REFERENCES "user"(id),

    -- Relazione con l'utente che ha caricato.
                               CONSTRAINT fk_file_resource_uploader
                                   FOREIGN KEY (uploaded_by_user_id)
                                       REFERENCES "user"(id),

    -- Eliminare una materia non elimina i file.
                               CONSTRAINT fk_file_resource_subject
                                   FOREIGN KEY (subject_id)
                                       REFERENCES subject(id)
                                       ON DELETE SET NULL,

    -- Ogni file fisico deve avere una chiave univoca.
                               CONSTRAINT uq_file_resource_storage_key
                                   UNIQUE (storage_key),

    -- Non accettiamo file vuoti.
                               CONSTRAINT chk_file_resource_size
                                   CHECK (size_bytes > 0)
);

-- Velocizza il recupero dei file personali.
CREATE INDEX idx_file_resource_owner
    ON file_resource(owner_user_id, created_at DESC);

-- Velocizza la ricerca per materia.
CREATE INDEX idx_file_resource_subject
    ON file_resource(subject_id);
