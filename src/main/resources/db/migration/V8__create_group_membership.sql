-- Gruppi accessibili esclusivamente tramite link d'invito.

-- Dati generali del gruppo. Il ruolo OWNER è registrato in group_membership,
-- evitando di duplicare il proprietario anche in questa tabella.
CREATE TABLE study_group (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             name VARCHAR(150) NOT NULL,
                             description VARCHAR(500),
                             created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                             CONSTRAINT ck_study_group_name_not_blank
                                 CHECK (length(btrim(name)) > 0)
);

-- Appartenenza dell'utente al gruppo e suo ruolo interno.
CREATE TABLE group_membership (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  group_id BIGINT NOT NULL,
                                  user_id BIGINT NOT NULL,
                                  role VARCHAR(20) NOT NULL DEFAULT 'MEMBER',
                                  joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                  CONSTRAINT fk_group_membership_group
                                      FOREIGN KEY (group_id) REFERENCES study_group(id)
                                          ON DELETE CASCADE,

                                  CONSTRAINT fk_group_membership_user
                                      FOREIGN KEY (user_id) REFERENCES "user"(id),

    -- Uno stesso utente non può iscriversi due volte allo stesso gruppo.
                                  CONSTRAINT uk_group_membership_group_user
                                      UNIQUE (group_id, user_id),

                                  CONSTRAINT ck_group_membership_role
                                      CHECK (role IN ('OWNER', 'MODERATOR', 'MEMBER'))
);

-- Impedisce che un gruppo abbia più di un OWNER.
CREATE UNIQUE INDEX uk_group_membership_single_owner
    ON group_membership(group_id)
    WHERE role = 'OWNER';


-- Velocizza il recupero dei gruppi a cui appartiene un utente.
CREATE INDEX idx_group_membership_user
    ON group_membership(user_id);